<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class ExamMaster extends Model
{
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | ACADEMIC YEAR
        |--------------------------------------------------------------------------
        */

        'academic_year_id',

        /*
        |--------------------------------------------------------------------------
        | EXAM
        |--------------------------------------------------------------------------
        */

        'exam_name',

        'exam_pattern_id',

        'standard_id',

        /*
        |--------------------------------------------------------------------------
        | MARKS
        |--------------------------------------------------------------------------
        */

        'max_marks',

        'passing_marks',

        /*
        |--------------------------------------------------------------------------
        | THEORY
        |--------------------------------------------------------------------------
        */

        'has_theory',

        'theory_max_marks',

        'theory_passing_marks',

        /*
        |--------------------------------------------------------------------------
        | ORAL
        |--------------------------------------------------------------------------
        */

        'has_oral',

        'oral_max_marks',

        'oral_passing_marks',

        /*
        |--------------------------------------------------------------------------
        | PRACTICAL
        |--------------------------------------------------------------------------
        */

        'has_practical',

        'practical_max_marks',

        'practical_passing_marks',

        /*
        |--------------------------------------------------------------------------
        | COMMON
        |--------------------------------------------------------------------------
        */

        'display_order',

        'is_active',
    ];


    /*
    |--------------------------------------------------------------------------
    | ACADEMIC YEAR
    |--------------------------------------------------------------------------
    */

    public function academicYear()
    {
        return $this->belongsTo(
            AcademicYear::class,
            'academic_year_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | EXAM PATTERN
    |--------------------------------------------------------------------------
    */

    public function examPattern()
    {
        return $this->belongsTo(
            ExamPattern::class,
            'exam_pattern_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | STANDARD
    |--------------------------------------------------------------------------
    */

    public function standard()
    {
        return $this->belongsTo(
            Standard::class,
            'standard_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | EXAM SUBJECTS
    |--------------------------------------------------------------------------
    */

    public function examSubjects()
    {
        return $this->hasMany(
            ExamMasterSubject::class,
            'exam_master_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | TEACHER SUBJECT ALLOCATIONS
    |--------------------------------------------------------------------------
    */

    public function teacherSubjectAllocations()
    {
        return $this->hasMany(
            TeacherSubjectAllocation::class,
            'exam_master_id'
        );
    }
}