<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

use App\Models\Subject;
use App\Models\Standard;
use App\Models\StandardWiseSubject;

class SubjectController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | INDEX
    |--------------------------------------------------------------------------
    */

    public function index(Request $request)
    {
        $query = StandardWiseSubject::with([
            'standard',
            'subject',
            'subject.subjectType',
        ]);

        if ($request->filled('standard_id')) {

            $query->where(
                'standard_id',
                (int) $request->standard_id
            );
        }

        $subjects = $query
            ->orderBy('standard_id')
            ->orderBy('sort_order')
            ->orderBy('id')
            ->get();

        $standards = Standard::where(
            'is_active',
            1
        )
            ->orderBy('display_order')
            ->get();

        return view(
            'subjects.index',
            compact(
                'subjects',
                'standards'
            )
        );
    }


    /*
    |--------------------------------------------------------------------------
    | CREATE
    |--------------------------------------------------------------------------
    */

    public function create()
    {
        $standards = Standard::where(
            'is_active',
            1
        )
            ->orderBy('display_order')
            ->get();

        $subjectTypes = DB::table(
            'subject_types'
        )
            ->where(
                'is_active',
                1
            )
            ->orderBy('id')
            ->get();

        $nextSortOrder =
            (
                StandardWiseSubject::max(
                    'sort_order'
                )
                ?? 0
            ) + 1;

        return view(
            'subjects.create',
            compact(
                'standards',
                'subjectTypes',
                'nextSortOrder'
            )
        );
    }


    /*
    |--------------------------------------------------------------------------
    | STORE
    |--------------------------------------------------------------------------
    |
    | Creates:
    |
    | 1. subjects
    | 2. standard_wise_subjects
    |
    | The ID generated by subjects is immediately used as:
    |
    | standard_wise_subjects.subject_id
    |
    */

    public function store(Request $request)
    {
        $request->validate([
            'standard_id' => [
                'required',
                'integer',
                'exists:standards,id',
            ],

            'subject_name' => [
                'required',
                'string',
                'max:255',
            ],

            'subject_code' => [
                'required',
                'string',
                'max:50',
            ],

            'short_name' => [
                'nullable',
                'string',
                'max:20',
            ],

            'subject_type_id' => [
                'required',
                'integer',
                'exists:subject_types,id',
            ],

            'sort_order' => [
                'nullable',
                'integer',
                'min:0',
            ],

            'is_optional' => [
                'nullable',
            ],

            'is_active' => [
                'nullable',
            ],
        ], [
            'standard_id.required' =>
                'Please select Standard.',

            'subject_name.required' =>
                'Please enter Subject Name.',

            'subject_code.required' =>
                'Please enter Subject Code.',

            'subject_type_id.required' =>
                'Please select Subject Type.',
        ]);

        try {

            DB::transaction(function () use ($request) {

                $standard = Standard::findOrFail(
                    (int) $request->standard_id
                );

                $subjectName = trim(
                    (string) $request->subject_name
                );

                $subjectCode = strtoupper(
                    trim(
                        (string) $request->subject_code
                    )
                );

                $shortName = $request->filled(
                    'short_name'
                )
                    ? trim(
                        (string) $request->short_name
                    )
                    : null;

                $sortOrder = (int) (
                    $request->sort_order ?? 0
                );

                $isOptional = $request->has(
                    'is_optional'
                )
                    ? 1
                    : 0;

                $isActive = $request->has(
                    'is_active'
                )
                    ? 1
                    : 0;

                /*
                |--------------------------------------------------------------------------
                | DUPLICATE CHECK FOR SELECTED STANDARD
                |--------------------------------------------------------------------------
                */

                $exists = StandardWiseSubject::where(
                    'standard_id',
                    $standard->id
                )
                    ->whereRaw(
                        'UPPER(TRIM(subject_name)) = ?',
                        [
                            strtoupper($subjectName)
                        ]
                    )
                    ->exists();

                if ($exists) {
                    throw new \Exception(
                        'This subject already exists for the selected Standard.'
                    );
                }

                /*
                |--------------------------------------------------------------------------
                | CREATE MASTER SUBJECT
                |--------------------------------------------------------------------------
                */

                $subject = Subject::create([
                    'subject_name' =>
                        $subjectName,

                    'subject_code' =>
                        $subjectCode,

                    'short_name' =>
                        $shortName,

                    'section_id' =>
                        $standard->section_id,

                    'subject_type_id' =>
                        (int) $request->subject_type_id,

                    'display_order' =>
                        $sortOrder,

                    'is_active' =>
                        $isActive,
                ]);

                /*
                |--------------------------------------------------------------------------
                | USE NEW SUBJECT ID
                |--------------------------------------------------------------------------
                */

                if (!$subject->id) {
                    throw new \Exception(
                        'Subject ID could not be generated.'
                    );
                }

                /*
                |--------------------------------------------------------------------------
                | CREATE STANDARD WISE MAPPING
                |--------------------------------------------------------------------------
                */

                StandardWiseSubject::create([
                    'standard_id' =>
                        $standard->id,

                    'subject_id' =>
                        $subject->id,

                    'standard_name' =>
                        $standard->standard_name,

                    'subject_name' =>
                        $subject->subject_name,

                    'sort_order' =>
                        $sortOrder,

                    'is_optional' =>
                        $isOptional,

                    'is_active' =>
                        $isActive,
                ]);
            });

            return redirect()
                ->route(
                    'subjects.index',
                    [
                        'standard_id' =>
                            $request->standard_id,
                    ]
                )
                ->with(
                    'success',
                    'Subject created successfully.'
                );

        } catch (\Throwable $e) {

            report($e);

            return back()
                ->withInput()
                ->with(
                    'error',
                    $e->getMessage()
                );
        }
    }


    /*
    |--------------------------------------------------------------------------
    | EDIT
    |--------------------------------------------------------------------------
    */

