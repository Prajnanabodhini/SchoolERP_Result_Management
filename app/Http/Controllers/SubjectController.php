                'subject',
                'standards',
                'subjectTypes'
            )
        );
    }


    /*
    |--------------------------------------------------------------------------
    | UPDATE
    |--------------------------------------------------------------------------
    |
    | Updates the master subject and the mapping.
    |
    | The Subject ID itself does not change.
    |
    */

    public function update(
        Request $request,
        StandardWiseSubject $subject
    ) {
        $request->validate([
            'standard_id' => [
                'required',
                'integer',
                'exists:standards,id',
            ],

            'subject_name' => [
                'required',
                'string',
                'max:255',
            ],

            'subject_code' => [
                'required',
                'string',
                'max:50',
            ],

            'short_name' => [
                'nullable',
                'string',
                'max:20',
            ],

            'subject_type_id' => [
                'required',
                'integer',
                'exists:subject_types,id',
            ],

            'sort_order' => [
                'nullable',
                'integer',
                'min:0',
            ],

            'is_optional' => [
                'nullable',
            ],

            'is_active' => [
                'nullable',
            ],
        ]);

        try {

            DB::transaction(function () use (
                $request,
                $subject
            ) {

                if (!$subject->subject_id) {
                    throw new \Exception(
                        'This mapping does not have a valid Subject ID.'
                    );
                }

                $masterSubject = Subject::findOrFail(
                    (int) $subject->subject_id
                );

                $standard = Standard::findOrFail(
                    (int) $request->standard_id
                );

                $subjectName = trim(
                    (string) $request->subject_name
                );

                $subjectCode = strtoupper(
                    trim(
                        (string) $request->subject_code
                    )
                );

                $shortName = $request->filled(
                    'short_name'
                )
                    ? trim(
                        (string) $request->short_name
                    )
                    : null;

                $sortOrder = (int) (
                    $request->sort_order ?? 0
                );

                $isOptional = $request->has(
                    'is_optional'
                )
                    ? 1
                    : 0;

                $isActive = $request->has(
                    'is_active'
                )
                    ? 1
                    : 0;

                /*
                |--------------------------------------------------------------------------
                | DUPLICATE MAPPING CHECK
                |--------------------------------------------------------------------------
                */

                $exists = StandardWiseSubject::where(
                    'standard_id',
                    $standard->id
                )
                    ->whereRaw(
                        'UPPER(TRIM(subject_name)) = ?',
                        [
                            strtoupper($subjectName)
                        ]
                    )
                    ->where(
                        'id',
                        '!=',
                        $subject->id
                    )
                    ->exists();

                if ($exists) {
                    throw new \Exception(
                        'This subject already exists for the selected Standard.'
                    );
                }

                /*
                |--------------------------------------------------------------------------
                | UPDATE SUBJECT MASTER
                |--------------------------------------------------------------------------
                */

                $masterSubject->update([
                    'subject_name' =>
                        $subjectName,

                    'subject_code' =>
                        $subjectCode,

                    'short_name' =>
                        $shortName,

                    'section_id' =>
                        $standard->section_id,

                    'subject_type_id' =>
                        (int) $request->subject_type_id,

                    'display_order' =>
                        $sortOrder,

                    'is_active' =>
                        $isActive,
                ]);

                /*
                |--------------------------------------------------------------------------
                | UPDATE MAPPING
                |--------------------------------------------------------------------------
                */

                $subject->update([
                    'standard_id' =>
                        $standard->id,

                    'subject_id' =>
                        $masterSubject->id,

                    'standard_name' =>
                        $standard->standard_name,

                    'subject_name' =>
                        $masterSubject->subject_name,

                    'sort_order' =>
                        $sortOrder,

                    'is_optional' =>
                        $isOptional,

                    'is_active' =>
                        $isActive,
                ]);
            });

            return redirect()
                ->route(
                    'subjects.index',
                    [
                        'standard_id' =>
                            $request->standard_id,
                    ]
                )
                ->with(
                    'success',
                    'Subject updated successfully.'
                );

        } catch (\Throwable $e) {

            report($e);

            return back()
                ->withInput()
                ->with(
                    'error',
                    $e->getMessage()
                );
        }
    }


    /*
    |--------------------------------------------------------------------------
    | DELETE
    |--------------------------------------------------------------------------
    |
    | Deletes only the selected Standard mapping.
    |
    | The master Subject is not physically deleted.
    |
    */

    public function destroy(
        StandardWiseSubject $subject
    ) {
        try {

            DB::transaction(function () use (
                $subject
            ) {

                $standardId =
                    $subject->standard_id;

                $subjectId =
                    $subject->subject_id;

                /*
                |--------------------------------------------------------------------------
                | DELETE MAPPING
                |--------------------------------------------------------------------------
                */

                $subject->delete();

                /*
                |--------------------------------------------------------------------------
                | DEACTIVATE MASTER IF UNUSED
                |--------------------------------------------------------------------------
                */

                if ($subjectId) {

                    $stillMapped =
                        StandardWiseSubject::where(
                            'subject_id',
                            $subjectId
                        )
                        ->where(
                            'is_active',
                            1
                        )
                        ->exists();

                    if (!$stillMapped) {

                        Subject::where(
                            'id',
                            $subjectId
                        )
                        ->update([
                            'is_active' =>
                                0,

                            'updated_at' =>
                                now(),
                        ]);
                    }
                }
            });

            return redirect()
                ->route(
                    'subjects.index',
                    [
                        'standard_id' =>
                            request(
                                'standard_id'
                            ),
                    ]
                )
                ->with(
                    'success',
                    'Subject Mapping deleted successfully.'
                );

        } catch (\Throwable $e) {

            report($e);

            return back()
                ->with(
                    'error',
                    $e->getMessage()
                );
        }
    }
}